"""
Creates student access codes.

  .venv/bin/python scripts/make-codes.py 100        # first batch
  .venv/bin/python scripts/make-codes.py 50 --add   # 50 more, keeps the existing ones

Writes:
  access-codes.xlsx (the codes, for you to hand out; never deployed, gitignored)
  netlify/edge-functions/_shared/code-hashes.js (SHA-256 of each code; this is all the server sees)
Then run ./scripts/deploy.sh.
"""
import hashlib
import json
import os
import secrets
import sys

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Font, PatternFill

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
XLSX = os.path.join(ROOT, "access-codes.xlsx")
HASHES = os.path.join(ROOT, "netlify", "edge-functions", "_shared", "code-hashes.js")
ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"  # no 0/O, 1/I/L: easy to read out loud


def new_code() -> str:
    raw = "".join(secrets.choice(ALPHABET) for _ in range(8))
    return f"PP-{raw[:4]}-{raw[4:]}"


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 100
    rows = []  # [number, code, assigned_to, notes]
    if "--add" in sys.argv and os.path.exists(XLSX):
        ws = load_workbook(XLSX).active
        rows = [list(r) for r in ws.iter_rows(min_row=2, values_only=True) if r and r[1]]
    existing = {r[1] for r in rows}
    target = len(rows) + n
    while len(rows) < target:
        c = new_code()
        if c not in existing:
            existing.add(c)
            rows.append([len(rows) + 1, c, "", ""])

    wb = Workbook()
    ws = wb.active
    ws.title = "Access codes"
    ws.append(["#", "Access code", "Given to", "Notes"])
    for r in rows:
        ws.append(r)
    for cell in ws[1]:
        cell.font = Font(bold=True, color="000000")
        cell.fill = PatternFill("solid", fgColor="F5B301")
    ws.column_dimensions["A"].width = 6
    ws.column_dimensions["B"].width = 18
    ws.column_dimensions["C"].width = 28
    ws.column_dimensions["D"].width = 40
    ws.freeze_panes = "A2"
    wb.save(XLSX)

    hashes = sorted(hashlib.sha256(r[1].encode()).hexdigest() for r in rows)
    with open(HASHES, "w") as f:
        f.write("// Generated by scripts/make-codes.py. SHA-256 of each student access code.\n")
        f.write(f"export const CODE_HASHES = new Set({json.dumps(hashes)});\n")
    print(f"{len(rows)} codes -> {XLSX}")


if __name__ == "__main__":
    main()
